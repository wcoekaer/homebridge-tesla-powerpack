const { test } = require('node:test');
const assert = require('node:assert/strict');
const { PowerpackPlatform } = require('../dist/platform');
const { mockController } = require('./helpers.cjs');

test('Homebridge battery level, threshold automations, direction sensors, and camera survive cache restore', { timeout: 15000 }, async t => {
  const m = await mockController(t);
  const { HomebridgeAPI } = await import('../node_modules/homebridge/dist/api.js');
  const api = new HomebridgeAPI(), created = [], removed = [];
  api.registerPlatformAccessories = (plugin, platform, items) => { assert.equal(plugin, '@wcoekaer/homebridge-tesla-powerpack'); assert.equal(platform, 'TeslaPowerpack'); created.push(...items); };
  api.unregisterPlatformAccessories = (_p, _n, items) => removed.push(...items);
  api.updatePlatformAccessories = () => {};
  const log = { info() {}, warn() {}, debug() {}, error() {} };
  const config = { ...m.config, platform: 'TeslaPowerpack' };
  const plugin = new PowerpackPlatform(log, config, api); t.after(() => api.emit('shutdown'));
  api.emit('didFinishLaunching'); await plugin.monitor.poll();
  const C = api.hap.Characteristic;
  assert.equal(created.length, 10);
  assert.equal(plugin.batteryService.getCharacteristic(C.BatteryLevel).value, 83);
  assert.equal(plugin.batteryService.getCharacteristic(C.ChargingState).value, C.ChargingState.NOT_CHARGING);
  assert.equal(plugin.sensors.get('discharging').getCharacteristic(C.ContactSensorState).value, 1);
  const camera = created.find(a => a.displayName.endsWith('Dashboard'));
  assert.ok(camera.getService(api.hap.Service.CameraRTPStreamManagement));
  m.data.soe.value.percentage = 19;
  m.data.meters.value.battery.instant_power = -1500;
  await plugin.monitor.poll();
  assert.equal(plugin.batteryService.getCharacteristic(C.BatteryLevel).value, 19);
  assert.equal(plugin.batteryService.getCharacteristic(C.ChargingState).value, C.ChargingState.CHARGING);
  assert.equal(plugin.thresholdSensors.get('20').getCharacteristic(C.ContactSensorState).value, 1);
  assert.equal(plugin.sensors.get('charging').getCharacteristic(C.ContactSensorState).value, 1);
  const stale = plugin.monitor.view(Date.now() + 91000); plugin.update(stale);
  assert.equal(plugin.thresholdSensors.get('20').getCharacteristic(C.StatusFault).value, C.StatusFault.GENERAL_FAULT);
  assert.equal(plugin.thresholdSensors.get('20').getCharacteristic(C.ContactSensorState).value, 1, 'stale data preserves the alarm');
  assert.ok(plugin.batteryService.getCharacteristic(C.BatteryLevel).statusCode !== 0);
  api.emit('shutdown');
  const next = new HomebridgeAPI(), duplicates = [];
  next.registerPlatformAccessories = (_p, _n, items) => duplicates.push(...items);
  next.unregisterPlatformAccessories = (_p, _n, items) => removed.push(...items); next.updatePlatformAccessories = () => {};
  const restored = new PowerpackPlatform(log, { ...config, camera: { enabled: false } }, next);
  for (const a of created) restored.configureAccessory(a);
  t.after(() => next.emit('shutdown')); next.emit('didFinishLaunching'); await restored.monitor.poll();
  assert.equal(duplicates.length, 0); assert.deepEqual(removed.map(a => a.UUID), [camera.UUID]);
  assert.ok(m.requests.every(r => r.method === 'GET' && !r.body));
});
